// Package postmortem renders a blameless postmortem DRAFT (Google SRE-style sections) from a compile
// report. It states only what execution demonstrated. Hypotheses are labelled as hypotheses, captured
// evidence is labelled as captured, and everything KAVIRA cannot know is listed as not established.
package postmortem

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/zyvorai/kavira/internal/bundle"
	"github.com/zyvorai/kavira/internal/compiler"
)

// text makes untrusted bundle text safe inside one Markdown line: no newlines, no raw HTML, no table or
// link syntax. Markdown viewers render embedded HTML, so angle brackets are escaped.
func text(s string) string {
	s = strings.Map(func(r rune) rune {
		switch {
		case r == '\n' || r == '\r' || r == '\t':
			return ' '
		case r < 0x20 || r == 0x7f:
			return -1
		}
		return r
	}, s)
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "|", "\\|", "`", "'", "[", "\\[", "]", "\\]", "*", "\\*", "_", "\\_", "#", "\\#")
	return strings.TrimSpace(r.Replace(s))
}

func mb(n int64) string {
	if n >= 1<<20 {
		return fmt.Sprintf("%.1f MiB (%d bytes)", float64(n)/(1<<20), n)
	}
	return fmt.Sprintf("%d bytes", n)
}

// Render returns the Markdown draft. It never contains a repair for a verdict the runner did not confirm.
func Render(b bundle.Bundle, rep compiler.Report) string {
	var w strings.Builder
	p := func(f string, a ...any) { fmt.Fprintf(&w, f+"\n", a...) }

	p("# Postmortem draft: %s", text(rep.ID))
	p("")
	p("**Status:** DRAFT, generated by KAVIRA from captured evidence. A human owns the final text.  ")
	p("**Service:** %s · **Class:** %s · **Compiled:** %s  ", text(rep.Service), text(rep.Class), text(rep.CompiledAt))
	p("**Authority:** %s decides. Exact replay: no (the failure is reconstructed, not replayed).", text(rep.Authority))
	p("")
	p("> How to read this draft. **Demonstrated** means the KAVIRA runner executed it just now. **Captured** means a person or tool supplied it in the evidence bundle and KAVIRA did not verify it. **Hypothesis** means a proposed explanation that execution has not confirmed as the production cause. Blameless: this describes conditions and systems, not people.")
	p("")

	p("## Summary")
	p("")
	p("- Symptom (captured): %s", text(rep.Symptom))
	p("- Verdict (demonstrated): `%s`. %s", rep.Verdict, text(rep.Summary))
	p("")

	p("## Impact (captured, not measured by KAVIRA)")
	p("")
	ev := b.Evidence
	any := false
	line := func(label, v string) { p("- %s: %s", label, v); any = true }
	if ev.RestartCount > 0 {
		line("Restarts", fmt.Sprint(ev.RestartCount))
	}
	if ev.P99Ms > 0 {
		line("Observed p99", fmt.Sprintf("%d ms", ev.P99Ms))
	}
	if ev.MemoryLimitBytes > 0 {
		line("Memory limit", mb(ev.MemoryLimitBytes))
	}
	if ev.ObservedPeakBytes > 0 {
		line("Observed peak", mb(ev.ObservedPeakBytes))
	}
	if ev.DiskLimitBytes > 0 {
		line("Disk quota", mb(ev.DiskLimitBytes))
	}
	if ev.ObservedUsedBytes > 0 {
		line("Observed used", mb(ev.ObservedUsedBytes))
	}
	if !any {
		p("- The bundle carries no impact numbers. User impact and duration are not established here.")
	}
	p("")

	p("## Timeline")
	p("")
	if len(b.Timeline) > 0 {
		p("Captured, in the order supplied. KAVIRA does not verify or re-order it.")
		p("")
		p("| When (captured) | Event (captured) |")
		p("| --- | --- |")
		for _, e := range b.Timeline {
			p("| %s | %s |", text(e.At), text(e.Event))
		}
	} else {
		p("The bundle has no timeline. Add `timeline` entries to the bundle to have them listed here.")
	}
	if ev.DeployChange != "" {
		p("")
		p("Deploy change (captured): %s", text(ev.DeployChange))
	}
	p("")
	p("Reconstruction run (demonstrated). This is the order KAVIRA executed arms in, not the production sequence:")
	p("")
	if len(rep.Experiments) == 0 {
		p("1. No experiment arm ran.")
	}
	for i, e := range rep.Experiments {
		p("%d. `%s`: %s, %d/%d failures. Changed: %s.", i+1, text(e.Name), text(e.Result), e.Failures, e.Attempts, text(e.Changed))
	}
	p("")

	p("## Root cause")
	p("")
	switch rep.Verdict {
	case "repair_held", "repair_failed":
		p("**Demonstrated:** under the captured condition the symptom reproduced in the reconstruction. That shows the captured condition is *sufficient* to produce this failure here. It does not show it is what happened in production.")
	case "not_reproduced":
		p("**Not demonstrated.** The captured condition did not reproduce the symptom when executed. No root cause is stated. Gather more evidence or widen the capture.")
	default:
		p("**Not demonstrated.** This incident class is outside what KAVIRA can reconstruct.")
	}
	p("")
	p("Hypotheses (not verdicts; `authoritative` is always false):")
	p("")
	if len(rep.Hypotheses) == 0 {
		p("- none proposed")
	}
	for _, h := range rep.Hypotheses {
		status := h.Status
		if status == "reproduced" {
			status = "reproduced in the reconstruction"
		}
		p("- **Hypothesis:** %s. Status: %s. %s", text(h.Name), text(status), text(h.Explanation))
	}
	p("")

	p("## Mitigation and repair")
	p("")
	if rep.Repair != nil && rep.Verdict == "repair_held" {
		p("**Demonstrated:** the repair arm held inside the bound in the reconstruction.")
		p("")
		p("```json")
		raw, _ := json.MarshalIndent(rep.Repair.Patch, "", "  ")
		p("%s", strings.ReplaceAll(string(raw), "```", "'''"))
		p("```")
		p("")
		p("**Do not apply this patch to production from a KAVIRA result alone.** Confirm the same factor on the real path first. `kavira export` writes a before/after regression check.")
	} else {
		p("No repair is stated: execution did not confirm one (`%s`). KAVIRA does not invent a repair for a failure it did not reproduce or could not repair.", rep.Verdict)
	}
	p("")

	p("## Not established by KAVIRA")
	p("")
	p("- That the captured condition is the production cause (only that it is sufficient in the reconstruction).")
	p("- Anything about traffic, data, or dependencies that the bundle does not name. Exact replay is never claimed.")
	p("- Duration, blast radius, and customer impact beyond the captured numbers above.")
	if notes := b.Evidence.Notes; len(notes) > 0 {
		p("")
		p("Capture notes (captured):")
		p("")
		for _, n := range notes {
			p("- %s", text(n))
		}
	}
	p("")

	p("## Action items (proposed, not verified)")
	p("")
	if rep.Verdict == "repair_held" {
		p("- [ ] Review the repair above with the service owner and test it on the real path.")
		p("- [ ] Keep the exported regression check in CI.")
	} else {
		p("- [ ] Collect more evidence so the incident can be reconstructed.")
	}
	p("- [ ] Run `kavira repeat` to see how stable the reconstruction is before relying on one verdict.")
	p("")

	p("## Lessons learned (for humans)")
	p("")
	p("- What went well:")
	p("- What went wrong:")
	p("- Where we got lucky:")
	p("")
	keys := make([]string, 0, len(rep.Measurements))
	for k := range rep.Measurements {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	p("## Appendix: measurements (demonstrated)")
	p("")
	for _, k := range keys {
		p("- %s: %s", text(k), text(fmt.Sprint(rep.Measurements[k])))
	}
	return w.String()
}
